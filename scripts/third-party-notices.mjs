// Regenerates THIRD-PARTY-NOTICES.md from Cargo.lock and apps/desktop/package-lock.json:
//
//   node scripts/third-party-notices.mjs
//
// Run it after changing dependencies. Needs `cargo` on the PATH.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const meta = JSON.parse(
  execFileSync("cargo", ["metadata", "--format-version", "1", "--locked"], { maxBuffer: 256 << 20, encoding: "utf8" }),
);
const own = new Set(meta.workspace_members);
const rust = meta.packages
  .filter((p) => !own.has(p.id))
  .map((p) => ({ name: p.name, version: p.version, license: p.license || "see the package", url: p.repository || `https://crates.io/crates/${p.name}` }));

const lock = JSON.parse(readFileSync("apps/desktop/package-lock.json", "utf8"));
const npm = Object.entries(lock.packages)
  .filter(([path, p]) => path && !p.dev && !p.devOptional)
  .map(([path, p]) => {
    const name = path.replace(/^.*node_modules\//, "");
    return { name, version: p.version, license: p.license || "see the package", url: `https://www.npmjs.com/package/${name}` };
  });

const unique = (list) => {
  const seen = new Map();
  for (const p of list) seen.set(`${p.name}@${p.version}`, p);
  return [...seen.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
};
const table = (list) =>
  ["| Package | Version | License |", "|---|---|---|", ...unique(list).map((p) => `| [${p.name}](${p.url}) | ${p.version} | ${p.license} |`)].join("\n");
const counts = (list) => {
  const by = new Map();
  for (const p of unique(list)) by.set(p.license, (by.get(p.license) || 0) + 1);
  return [...by.entries()].sort((a, b) => b[1] - a[1]).map(([l, n]) => `- ${l}: ${n}`).join("\n");
};

const out = `# Third-party notices

Vessel is licensed under MIT or Apache-2.0, at your option (see \`LICENSE-MIT\` and \`LICENSE-APACHE\`).
The programs built from this repository include the open-source packages listed below, each under
its own license. The license text of every package ships inside the package itself, at the link
given. This file is generated by \`scripts/third-party-notices.mjs\`.

The interface uses the IBM Plex Sans and IBM Plex Mono typefaces (SIL Open Font License 1.1),
through the \`@fontsource\` packages listed under JavaScript.

## Rust crates

${table(rust)}

## JavaScript packages (bundled into the app's interface)

${table(npm)}

## Licenses in use

Rust:

${counts(rust)}

JavaScript:

${counts(npm)}
`;
writeFileSync("THIRD-PARTY-NOTICES.md", out);
console.log(`THIRD-PARTY-NOTICES.md: ${unique(rust).length} crates, ${unique(npm).length} npm packages`);
